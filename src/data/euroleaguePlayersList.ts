// Convert filenames to player objects
export const euroleaguePlayersData: Player[] = euroleagueImageFiles.map((filename, index) => {
  const playerName = filenameToPlayerName(filename);
  const team = getEuroleagueTeam(playerName);
  
  return {
    id: 101 + index, // Start from 101 to avoid conflicts with NBA players
    name: playerName,
    team: team,
    league: "Euroleague" as const,
    imageUrl: "",
  };
});

